export function getRefrigerationGroup(slug) {
  return REFRIGERATION_GROUPS.find(
    (group) => group.slug === slug
  )
}

export function getRefrigerationSubcategory(groupSlug, childSlug) {
  const group = getRefrigerationGroup(groupSlug)

  return group?.children.find(
    (child) => child.slug === childSlug
  )
}